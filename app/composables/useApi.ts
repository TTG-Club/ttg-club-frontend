/**
 * Клиент запросов к API сайта (`$api` из плагина `api`): в браузере он
 * продлевает истёкшую сессию и повторяет запрос. Все запросы к API идут
 * через него, а не через `$fetch`; напрямую `$fetch` вызывает лишь код самой
 * сессии (`useUser`).
 *
 * Вне контекста Nuxt на сервере (после `await` в обработчике) отдаёт
 * обычный `$fetch`: продлевать сессию там всё равно нельзя.
 * @returns клиент запросов
 */
export function useApi(): typeof $fetch {
  return tryUseNuxtApp()?.$api ?? $fetch;
}
