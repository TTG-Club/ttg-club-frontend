<script setup lang="ts">
  import { SectionLayout } from '~section/layout';
  import { useWorkshopEditPage } from '~workshop/composables';
  import { WorkshopEditFrame } from '~workshop/entry-state';
  import { WorkshopAccessGate } from '~workshop/gate';
  import { ItemEditor } from '~workshop/items';
  import {
    fetchReferenceEntry,
    ITEM_EDITOR_TEXT,
    ITEMS_REFERENCE_PATH,
    ITEMS_WORKSHOP_KEY,
    parseWorkshopItem,
  } from '~workshop/model';

  definePageMeta({ layout: 'section' });

  // Служебная страница, поисковикам она не нужна
  useSeoMeta({
    title: ITEM_EDITOR_TEXT.editTitle,
    robots: 'noindex, nofollow',
  });

  const {
    entry,
    isLoading,
    isNotFound,
    isError,
    version,
    reload,
    handleSaved,
  } = useWorkshopEditPage({
    sectionKey: ITEMS_WORKSHOP_KEY,
    fetchEntry: (slug) =>
      fetchReferenceEntry(`${ITEMS_REFERENCE_PATH}/${slug}`),
    parse: parseWorkshopItem,
  });
</script>

<template>
  <SectionLayout :title="ITEM_EDITOR_TEXT.editTitle">
    <WorkshopAccessGate>
      <!-- Редактор разбирает разметку средствами браузера -->
      <ClientOnly>
        <WorkshopEditFrame
          :api-section="ITEMS_WORKSHOP_KEY"
          :entry-id="entry?.id"
          :version="version"
          :is-loading="isLoading"
          :is-not-found="isNotFound"
          :is-error="isError"
          @reload="reload"
        >
          <ItemEditor
            v-if="entry"
            :key="version"
            :item="entry"
            @saved="handleSaved"
          />
        </WorkshopEditFrame>
      </ClientOnly>
    </WorkshopAccessGate>
  </SectionLayout>
</template>
